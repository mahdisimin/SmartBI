func TestQA_MonthKey_MatchesIntlPersianCalendar(t *testing.T) {
	for _, b := range qaJalaliBoundaries {
		for _, c := range []struct{ ts, want string }{{b.startUTC, b.startKey}, {b.beforeUTC, b.beforeKey}} {
			ts, err := time.Parse(time.RFC3339, c.ts)
			if err != nil {
				t.Fatal(err)
			}
			if got := monthKey(ts); got != c.want {
				t.Errorf("monthKey(%s = %s Tehran) = %s, want %s", c.ts, ts.In(dashboardLocation).Format("2006-01-02 15:04:05"), got, c.want)
			}
		}
	}
	if len(qaJalaliBoundaries) < 48 {
		t.Fatalf("oracle too small: %d", len(qaJalaliBoundaries))
	}
}

// Every hour over ~3 years: the week key must be a Saturday (Tehran), on or
// before the event's Tehran date, and fewer than 7 days before it.
func TestQA_WeekStartKey_SaturdayProperty(t *testing.T) {
	for ts := time.Date(2024, 1, 1, 0, 0, 0, 0, time.UTC); ts.Before(time.Date(2027, 1, 1, 0, 0, 0, 0, time.UTC)); ts = ts.Add(time.Hour) {
		key := weekStartKey(ts)
		start, err := time.ParseInLocation("2006-01-02", key, dashboardLocation)
		if err != nil {
			t.Fatalf("bad key %q: %v", key, err)
		}
		local := ts.In(dashboardLocation)
		day := time.Date(local.Year(), local.Month(), local.Day(), 0, 0, 0, 0, dashboardLocation)
		if start.Weekday() != time.Saturday {
			t.Fatalf("weekStartKey(%s) = %s is a %s", ts, key, start.Weekday())
		}
		if diff := int(day.Sub(start).Hours()/24 + 0.5); diff < 0 || diff > 6 {
			t.Fatalf("weekStartKey(%s Tehran %s) = %s: %d days away", ts, local.Format("Mon 2006-01-02 15:04"), key, diff)
		}
	}
}

// A Friday 23:59 Tehran event belongs to the week that started the previous
// Saturday; one minute later (Saturday 00:00 Tehran) starts a new week — even
// though both are Friday in UTC.
func TestQA_WeekStartKey_TehranMidnightBoundary(t *testing.T) {
	fri := time.Date(2026, 9, 25, 20, 29, 0, 0, time.UTC) // Fri 23:59 Tehran
	sat := fri.Add(time.Minute)                           // Sat 00:00 Tehran, still Friday UTC
	if got := weekStartKey(fri); got != "2026-09-19" {
		t.Errorf("Fri 23:59 Tehran -> %s, want 2026-09-19", got)
	}
	if got := weekStartKey(sat); got != "2026-09-26" {
		t.Errorf("Sat 00:00 Tehran -> %s, want 2026-09-26", got)
	}
}
